/// Map a negotiated DH group id to its RFC 7919 prime (hex), or
/// `None` for the NULL group / an unknown id.
pub fn ffdhe_prime_hex(dhgid: u8) -> Option<&'static str> {
    Some(match dhgid {
        NVME_AUTH_DHGROUP_2048 => FFDHE2048_PRIME_HEX,
        NVME_AUTH_DHGROUP_3072 => FFDHE3072_PRIME_HEX,
        NVME_AUTH_DHGROUP_4096 => FFDHE4096_PRIME_HEX,
        NVME_AUTH_DHGROUP_6144 => FFDHE6144_PRIME_HEX,
        NVME_AUTH_DHGROUP_8192 => FFDHE8192_PRIME_HEX,
        _ => return None,
    })
}
