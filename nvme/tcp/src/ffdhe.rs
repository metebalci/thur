//! RFC 7919 finite-field Diffie-Hellman (FFDHE) group primes.
//!
//! DH-HMAC-CHAP (NVMe Base 8.13) negotiates one of the RFC 7919
//! FFDHE groups (or the NULL group). The generator is g = 2 for all
//! five groups; only the prime differs. These constants are the prime
//! `p` in uppercase hex, extracted verbatim from OpenSSL's built-in
//! ffdhe group tables (the same library this crate links for the DH
//! modexp), so the bytes cannot drift from what a peer using OpenSSL
//! or the Linux kernel ffdhe templates computes. Every prime is a
//! safe prime whose top and bottom 64 bits are all ones (the RFC 7919
//! construction); `auth::tests` re-checks primality + structure at
//! test time via OpenSSL BN.

