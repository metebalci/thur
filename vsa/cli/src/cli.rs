#[derive(Subcommand)]
enum IscsiAction {
    /// CHAP user lifecycle.
    Users {
        #[command(subcommand)]
        action: IscsiUsersAction,
    },

    /// Mutual-CHAP target credential.
    ///
    /// Singleton (one identity the target presents back to every
    /// mutual-CHAP-enabled initiator). Stored at the top level of
    /// `iscsi-users.json` as `target_username` / `target_password`.
    Target {
        #[command(subcommand)]
        action: IscsiTargetAction,
    },
}

#[derive(Subcommand)]
enum IscsiUsersAction {
    /// List every CHAP user.
    List {
        /// Emit JSON for automation.
        #[arg(long)]
        json: bool,
    },

    /// Add a new CHAP user.
    ///
    /// Refuses if the username already exists; use `rotate` to
    /// change a password. CHAP secret must be at least 12 bytes
    /// (RFC 3720 §11.1.4).
    Add {
        /// Username (CHAP identity the initiator presents).
        name: String,

        /// Password as a CLI arg. Mutually exclusive with `--password-stdin`.
        ///
        /// Note: appears in shell history and process listings. Prefer
        /// `--password-stdin` for production / config-management use.
        #[arg(long, conflicts_with = "password_stdin")]
        password: Option<String>,

        /// Read the password from stdin (single line, trailing
        /// newline stripped). Mutually exclusive with `--password`.
        #[arg(long)]
        password_stdin: bool,

        /// Enable mutual CHAP (target authenticates back to the
        /// initiator). Requires `iscsi target set` to have been run.
        #[arg(long)]
        mutual_chap: bool,

        /// Partition the user is fenced to (VTL only; VSA ignores).
        #[arg(long)]
        partition: Option<String>,
    },

    /// Remove a CHAP user.
    Remove {
        /// Username to remove.
        name: String,
    },

    /// Disable a user without removing the entry.
    ///
    /// Login attempts get a "disabled" rejection. Distinct from
    /// `remove` so the entry keeps its audit-history continuity
    /// and can be re-enabled later without re-sharing the password.
    Disable {
        /// Username to disable.
        name: String,
    },

    /// Re-enable a previously disabled user.
    Enable {
        /// Username to re-enable.
        name: String,
    },

    /// Rotate a user's password with a grace window.
    ///
    /// Both the old and new password authenticate until the grace
    /// window expires (default 24h). Revert with `rotate USER
    /// --cancel`. Refuses if a rotation is already in progress
    /// (cancel the existing one first to avoid orphaning the
    /// previous-previous password).
    Rotate {
        /// Username to rotate.
        name: String,

        /// New password as a CLI arg. Mutually exclusive with
        /// `--password-stdin`.
        #[arg(long, conflicts_with_all = ["password_stdin", "cancel"])]
        password: Option<String>,

        /// Read the new password from stdin (single line).
        #[arg(long, conflicts_with = "cancel")]
        password_stdin: bool,

        /// Grace window during which both passwords remain valid.
        /// Humantime: `24h`, `5m`, `1d12h`. Default `24h`.
        #[arg(long, default_value = "24h", conflicts_with = "cancel")]
        grace: String,

        /// Cancel an in-flight rotation: drop the new password,
        /// restore the previous one as sole current. Errors if no
        /// rotation is in progress.
        #[arg(long)]
        cancel: bool,
    },
}

#[derive(Subcommand)]
enum IscsiTargetAction {
    /// Show the current target identity (password value hidden).
    Show {
        /// Emit JSON for automation.
        #[arg(long)]
        json: bool,
    },

    /// Set both target_username and target_password.
    ///
    /// Overwrites any prior values. Required when any user has
    /// `mutual_chap: true`. Password must be at least 12 bytes
    /// (RFC 3720 §11.1.4).
    Set {
        /// Target username (sent in `CHAP_N` during mutual auth).
        #[arg(long)]
        username: String,

        /// Password as a CLI arg. Mutually exclusive with `--password-stdin`.
        #[arg(long, conflicts_with = "password_stdin")]
        password: Option<String>,

        /// Read the password from stdin (single line).
        #[arg(long)]
        password_stdin: bool,
    },

    /// Clear both target_username and target_password.
    ///
    /// Mutual-CHAP requests fail with "Target password not
    /// configured" afterward.
    Clear,
}

