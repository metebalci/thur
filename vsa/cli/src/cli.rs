#[derive(Subcommand)]
enum CloudAction {
    /// First-party cloud-backend throughput benchmark (daemon-down).
    ///
    /// Drives parallel upload / download / delete against the named
    /// backend(s) defined under `cloud.backends:` in the YAML conffile
    /// and prints parseable `[BENCH]` lines. Issues real cloud API
    /// calls and transfers real bytes — runs against the operator's
    /// bucket, so expect non-zero cost on metered backends.
    Benchmark {
        /// Backend name to benchmark. Repeatable.
        ///
        /// Defaults to every backend defined under `cloud.backends:`
        /// in the YAML conffile (lexicographic order).
        #[arg(long = "backend")]
        backends: Vec<String>,

        /// GiB per cell. Default 32.
        #[arg(long, default_value_t = 32)]
        total_gb: usize,

        /// MiB per upload. Default 8 matches the FastCDC chunk average.
        #[arg(long, default_value_t = 8)]
        chunk_size_mb: usize,

        /// Parallel in-flight uploads per cell. Default 16.
        #[arg(long, default_value_t = 16)]
        concurrency: usize,

        /// Sweep chunk size across this comma-separated list.
        #[arg(long, value_delimiter = ',')]
        chunk_size_mb_sweep: Vec<usize>,

        /// Sweep concurrency across this comma-separated list.
        #[arg(long, value_delimiter = ',')]
        concurrency_sweep: Vec<usize>,

        /// Skip the download phase.
        #[arg(long)]
        skip_download: bool,

        /// Bypass the sweep-preview prompt (scripted runs).
        #[arg(long)]
        yes: bool,
    },
}

#[derive(Subcommand)]
enum VolumeAction {
    /// Create a new volume.
    ///
    /// Tries the daemon's admin socket first; falls back to a
    /// daemon-down manifest write under `data_dir` when the
    /// socket is unreachable. The chosen backend, page size, and
    /// dedup scope are sticky for the volume's lifetime.
    Create {
        /// Volume name (1-64 chars: letters, digits, '-', '_').
        name: String,

        /// Logical volume size, e.g. `1T`, `500G`, `4096`.
        ///
        /// Binary units only: K=2^10, M=2^20, G=2^30, T=2^40, P=2^50.
        /// Bare integer = bytes. Trailing `B` / `iB` is accepted but
        /// ignored. Must be a multiple of the sector size (4 KiB).
        #[arg(long)]
        size: String,

        /// Cloud backend name to bind this volume to.
        ///
        /// Required when thurvsa.yaml defines multiple entries under
        /// `cloud.backends`; inferred when only one backend exists.
        #[arg(long)]
        backend: Option<String>,

        /// Page size — chunk unit for cloud upload + disk cache.
        ///
        /// Power of two, multiple of the sector size. Default 64K.
        #[arg(long, default_value = "64K")]
        page_size: String,

        /// Dedup scope: `local` (default) or `global`.
        #[arg(long, value_parser = ["local", "global"], default_value = "local")]
        dedup: String,

        /// Mark the volume Write-Once-Read-Many.
        #[arg(long)]
        worm: bool,

        /// Enable at-rest encryption (requires --keystore).
        ///
        /// The daemon mints an AES-256 DEK at create time (unless
        /// --key-file supplies one) and wraps it with the --keystore
        /// backend. Sticky for the volume's lifetime.
        #[arg(long, requires = "keystore")]
        encrypt: bool,

        /// Supply the at-rest DEK from PATH instead of minting one.
        ///
        /// PATH must contain a 64-char hex string (32 raw bytes = AES-256).
        /// `openssl rand -hex 32` produces a valid file. Requires
        /// `--encrypt`; sticky for the volume's lifetime.
        #[arg(long, value_name = "PATH", requires = "encrypt")]
        key_file: Option<std::path::PathBuf>,

        /// Keystore backend that wraps this volume's DEK.
        ///
        /// References a name in `keystore.backends:` (YAML conffile).
        /// Required together with `--encrypt`. Sticky for the volume's
        /// lifetime.
        #[arg(long, value_name = "NAME", requires = "encrypt")]
        keystore: Option<String>,

        /// Where the DEK is minted (requires --encrypt).
        ///
        /// `daemon` (default) uses the daemon's OsRng then asks the
        /// backend to wrap. `backend` uses KMS GenerateDataKey or
        /// Vault transit/datakey (HSM-grade RNG, one fewer
        /// round-trip). Ignored for the `local` backend.
        #[arg(long, value_parser = ["daemon", "backend"], requires = "encrypt")]
        dek_source: Option<String>,

        /// Initial SYNCHRONIZE CACHE durability tier (mutable later
        /// via `volume modify --sync-after`).
        ///
        /// `cloud` (default) — fsync waits until bytes are in cloud
        /// object store. Safest; matches the cloud-backed-storage
        /// contract.
        ///
        /// `disk` — fsync waits until bytes are in the local pool.
        /// Faster; loses on daemon-host disk failure before the
        /// upload worker drains.
        ///
        /// `memory` — fsync is a no-op; dirty pages stay in RAM
        /// until the periodic flush worker tick. Fastest; loses on
        /// any crash. ZFS sync=disabled equivalent.
        #[arg(long, value_parser = ["cloud", "disk", "memory"], default_value = "cloud")]
        sync_after: String,

        /// Pin this volume to LUN N.
        ///
        /// Default auto-assigns the smallest unused LUN. Pinned LUNs
        /// keep `/dev/disk/by-path/...-lun-N` references stable when
        /// sibling volumes are added or removed. Refuses if N is
        /// already bound.
        #[arg(long, value_name = "N")]
        lun: Option<u64>,
    },

    /// List every volume.
    ///
    /// Reads the live LUN map via the admin socket; falls back to
    /// walking `<data_dir>/volumes/` when the socket is
    /// unreachable. The socket view includes the assigned LUN per
    /// volume; the offline view doesn't.
    List {
        /// Emit the response as JSON for automation.
        #[arg(long)]
        json: bool,
    },

    /// Show one volume's manifest.
    Info {
        /// Volume name.
        name: String,

        /// Emit the manifest as JSON for automation.
        #[arg(long)]
        json: bool,
    },

    /// Destroy a volume.
    ///
    /// Unregisters the volume from the live LUN map and removes
    /// its on-disk artifacts (manifest + page index). Per-volume
    /// chunks remain in the pool until the next GC sweep.
    /// Daemon-routed only — refuses with "is the daemon running?"
    /// when the admin socket is unreachable.
    Destroy {
        /// Volume name.
        name: String,

        /// Confirm destruction. Without this flag the command
        /// refuses; the volume contents are gone after a destroy.
        #[arg(long)]
        force: bool,
    },

    /// Modify a live volume's mutable settings.
    ///
    /// Daemon-routed only — refuses if the admin socket is
    /// unreachable. The flip takes effect on the next host
    /// SYNCHRONIZE CACHE; in-flight SYNCs finish under the
    /// previous mode.
    ///
    /// **The contract change is not signalled to the SCSI
    /// initiator.** A host fsync-heavy workload silently gains or
    /// loses its durability guarantee on a flip; pair flips with
    /// workload-level awareness.
    Modify {
        /// Volume name.
        name: String,

        /// New SYNCHRONIZE CACHE durability tier.
        ///
        /// See `volume create --sync-after` for the per-tier
        /// semantic. Flipping `cloud → memory` is the dangerous
        /// direction — host fsyncs that previously meant
        /// "cloud-durable" silently become no-ops; bytes the host
        /// believes are persisted are lost on the next crash.
        #[arg(long, value_parser = ["cloud", "disk", "memory"])]
        sync_after: String,
    },

    /// Per-volume key-management operations.
    Key {
        #[command(subcommand)]
        action: KeyAction,
    },
}

#[derive(Subcommand)]
enum KeyAction {
    /// Move a volume's DEK to a different keystore backend.
    ///
    /// Unwraps the existing DEK from the current keystore backend,
    /// asks the new backend to rewrap the same DEK, and updates the
    /// manifest atomically. Volume data is NOT rewritten — only the
    /// wrap-target moves. Daemon-down only; stop thurvsad first.
    Migrate {
        /// Volume name.
        name: String,

        /// New keystore backend name.
        ///
        /// Must exist under `keystore.backends:` in the YAML conffile.
        /// Refuses if it matches the volume's current keystore backend.
        #[arg(long)]
        to: String,

        /// Delete the local-keystore sidecar after migrating away.
        ///
        /// Off by default so the operator can roll back by reverting
        /// the manifest if the new backend turns out to be
        /// misconfigured. Re-run with this flag once you've verified
        /// the new backend works.
        #[arg(long)]
        purge_local: bool,
    },

    /// Export a volume's DEK to a passphrase-sealed file (JWE/PBES2).
    ///
    /// Cross-region DR + audit-compliant key custody. Output is a
    /// JWE Compact string (RFC 7516 + 7518 PBES2-HS512+A256KW /
    /// A256GCM), one base64 token storable in any escrow vehicle
    /// (vault, sealed envelope, secrets manager). Cryptographically
    /// bound to the volume UUID — a stolen envelope is useless
    /// against any other volume. Daemon-down only.
    Export {
        /// Volume name.
        name: String,

        /// Output file path. Refuses if the file already exists.
        #[arg(long)]
        to: std::path::PathBuf,

        /// PBKDF2 iteration count. Default tuned for ~1 s on
        /// modern x86_64; raise for stronger work factor at the
        /// cost of slower export/import. Mirrors
        /// `shared_keystore::passphrase_envelope::DEFAULT_P2C`.
        #[arg(long, default_value_t = 600_000)]
        iter: u32,
    },

    /// Import a passphrase-sealed DEK envelope into a volume.
    ///
    /// Unwraps the JWE envelope produced by `volume key export` and
    /// rewraps the DEK into the named keystore backend (or the
    /// single configured one). Refuses if the envelope's bound UUID
    /// doesn't match the volume's UUID, or if the volume's current
    /// keystore already holds an unwrappable DEK (use
    /// `volume key migrate` to swap wrap targets in place).
    /// Daemon-down only.
    Import {
        /// Volume name.
        name: String,

        /// JWE Compact envelope file path (produced by
        /// `volume key export`).
        #[arg(long)]
        from: std::path::PathBuf,

        /// Target keystore backend name to rewrap into. Optional if
        /// `keystore.backends:` defines exactly one entry.
        #[arg(long)]
        keystore: Option<String>,
    },
}

